"""Промпты постобработки. Меняйте текст здесь — перезапуск worker'а не требует пересборки."""
from .schemas import JobOptions

SYSTEM = (
    "Ты — редактор расшифровок. Работаешь строго с предоставленным текстом, "
    "не выдумываешь фактов и не добавляешь того, чего не было сказано. "
    "Отвечай на языке исходного текста, если не указано иное."
)

TEMPLATES: dict[str, str] = {
    "summary": (
        "Сделай краткое содержание расшифровки.\n"
        "Формат: 3–7 предложений связного текста, затем список ключевых тезисов.\n"
        "Сохрани имена, числа, даты и термины без искажений.\n\n"
        "РАСШИФРОВКА:\n{text}"
    ),
    "minutes": (
        "Составь протокол встречи по расшифровке.\n"
        "Структура:\n"
        "## Участники (если определимы)\n"
        "## Обсуждённые вопросы\n"
        "## Принятые решения\n"
        "## Задачи (что / кто / срок)\n"
        "## Открытые вопросы\n"
        "Если раздел не подтверждается текстом — напиши «не зафиксировано».\n\n"
        "РАСШИФРОВКА:\n{text}"
    ),
    "bullets": (
        "Преобразуй расшифровку в структурированный конспект: вложенные маркированные списки, "
        "заголовки по смысловым блокам, без воды и повторов.\n\n"
        "РАСШИФРОВКА:\n{text}"
    ),
    "translate": (
        "Переведи расшифровку на язык: {target_language}. "
        "Сохрани абзацы, имена собственные и терминологию. Верни только перевод.\n\n"
        "РАСШИФРОВКА:\n{text}"
    ),
    "custom": "{post_instruction}\n\nРАСШИФРОВКА:\n{text}",
}


def build(options: JobOptions, text: str) -> str:
    template = TEMPLATES[options.post_action]
    return template.format(
        text=text,
        target_language=options.target_language or "English",
        post_instruction=options.post_instruction or "Кратко перескажи текст.",
    )
